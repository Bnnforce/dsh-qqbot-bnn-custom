/**
 * /唤醒抽奖 —— 打开「唤醒抽奖」卡片（R5.6）
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * 为什么需要这个命令
 *   botplay 卡片必须有**触发入口**，官方契约靠 botplay-events.json 登记事件，
 *   但卡片本身不会自己出现 —— 需要一个命令把它"点着"。
 *
 *   现有的 12 张卡都各有一个命令（日历/骰子/小店/签到…），
 *   wake-lottery 是 R5.6 新加的，必须补一个，否则
 *   `check-card-commands.mjs` 会报「卡片没有对应命令」，
 *   而且她在群里发的卡片也没法用 /命令 复现。
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * 用法：
 *   /唤醒抽奖   → 发一张唤醒抽奖卡片（群友可点按钮抽）
 *
 * 注意：这个命令只是**把卡片开出来**，不直接抽奖。
 *       真正抽奖在卡片按钮回调里（botplay/wake-lottery.mjs 的 onClick）。
 */
import { cardCommand } from '../lib/pure/card-kit.mjs';

export default cardCommand({
  id: 'wake-lottery',
  names: ['唤醒抽奖', 'wake-lottery', 'wl'],
  description: '打开唤醒抽奖卡片（她留了盒子时抽一次）',
  usage: '/唤醒抽奖',
});
